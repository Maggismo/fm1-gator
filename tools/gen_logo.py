"""The boot logo: firmware/apps/APP/logo.png -> fw_logo.h, 240 x 240 at most, 256 colours (one byte a pixel + an RGB565 palette).

  tools/gen_logo.py OUT.h LOGO.png [--preview PREVIEW.png]

Any size or aspect: fitted into 240 x 240 and centred on black. Near-black (the art's dark texture) becomes black, so
the picture meets the panel's black edge. No logo file: FW_LOGO 0 and the splash is text only."""
import argparse
import sys
from pathlib import Path

SIDE = 240
BLACK_BELOW = 28


def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def rows(values, per_line, fmt):
    return ",\n".join("    " + ", ".join(fmt % v for v in values[i:i + per_line])
                      for i in range(0, len(values), per_line))


def convert(path):
    from PIL import Image
    im = Image.open(path).convert("RGB")
    scale = min(SIDE / im.width, SIDE / im.height)
    w, h = max(1, round(im.width * scale)), max(1, round(im.height * scale))
    im = im.resize((w, h), Image.LANCZOS)
    dark = im.convert("L").point(lambda v: 255 if v < BLACK_BELOW else 0)
    im.paste((0, 0, 0), mask=dark)
    q = im.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:256 * 3]
    pal += [0] * (256 * 3 - len(pal))
    return q, [rgb565(*pal[i * 3:i * 3 + 3]) for i in range(256)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("logo", type=Path)
    ap.add_argument("--preview", type=Path)
    a = ap.parse_args()
    head = "/* generated by tools/gen_logo.py, do not edit */\n"
    if not a.logo.exists():
        a.out.write_text(head + "#define FW_LOGO 0\n")
        print(f"logo: none ({a.logo})")
        return 0
    q, pal = convert(a.logo)
    px = list(q.tobytes())
    a.out.write_text(head + "#define FW_LOGO 1\n"
                     f"#define FW_LOGO_W {q.width}u\n#define FW_LOGO_H {q.height}u\n"
                     f"static const uint16_t FW_LOGO_PAL[256] = {{\n{rows(pal, 12, '0x%04X')}\n}};\n"
                     f"static const uint8_t FW_LOGO_PX[{len(px)}] = {{\n{rows(px, 24, '%d')}\n}};\n")
    if a.preview:
        q.convert("RGB").save(a.preview)
    print(f"logo: {a.logo.name} -> {q.width} x {q.height}, 256 colours, {len(px) + 512} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
