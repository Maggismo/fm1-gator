import math
import sys
from pathlib import Path

MCLK = {"44": 192e6 / 17, "48": 160e6 / 13}   # firmware/sys/fw_rate.h
SINE_N = 1024


def note_inc(n, fs):
    return round(440.0 * 2 ** ((n - 69) / 12) / fs * 2 ** 32) & 0xFFFFFFFF


def sine(i):
    return round(32767 * math.sin(2 * math.pi * i / SINE_N))


def rows(values, per_line, fmt):
    chunks = [values[i:i + per_line] for i in range(0, len(values), per_line)]
    return ",\n".join("    " + ", ".join(fmt(v) for v in c) for c in chunks)


def main(out, khz):
    fs = MCLK[khz] / 256
    text = "\n".join([
        "/* generated by tools/gen_tables.py: do not edit */",
        "#pragma once",
        f"#define FW_SINE_N {SINE_N}u",
        "static const uint32_t FW_NOTE_INC[128] = {",
        rows([note_inc(n, fs) for n in range(128)], 6, lambda v: f"0x{v:08X}u"),
        "};",
        "static const int16_t FW_SINE[FW_SINE_N] = {",
        rows([sine(i) for i in range(SINE_N)], 12, str),
        "};",
        "",
    ])
    Path(out).write_text(text)
    print(f"tables: {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "44")
